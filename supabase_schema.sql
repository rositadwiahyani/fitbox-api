-- ==============================================================================
-- FITBOX DATABASE SCHEMA (SUPABASE / POSTGRESQL)
-- ==============================================================================
-- Skema tabel untuk aplikasi langganan katering sehat FitBox
-- Jalankan skrip ini di SQL Editor pada Dashboard Supabase Anda.

-- 1. EXTENSIONS
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- ==============================================================================
-- 2. TABEL PACKAGES (Daftar Paket Katering & Nutrisi)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.packages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    goal VARCHAR(50) NOT NULL CHECK (goal IN ('turun', 'maintenance', 'naik')),
    calories INTEGER NOT NULL CHECK (calories > 0),
    protein NUMERIC(6, 2) DEFAULT 0,
    carbs NUMERIC(6, 2) DEFAULT 0,
    fats NUMERIC(6, 2) DEFAULT 0,
    fiber NUMERIC(6, 2) DEFAULT 0,
    price_per_day NUMERIC(12, 2) NOT NULL CHECK (price_per_day > 0),
    image_url TEXT,
    description TEXT,
    menu_sample TEXT,
    highlights JSONB DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- Index pencarian paket
CREATE INDEX IF NOT EXISTS idx_packages_goal ON public.packages (goal);
CREATE INDEX IF NOT EXISTS idx_packages_calories ON public.packages (calories);

-- ==============================================================================
-- 3. TABEL PROFILES (Profil Pengguna Terdaftar)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    name VARCHAR(255),
    phone VARCHAR(50),
    address TEXT,
    updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW())
);

-- ==============================================================================
-- 4. TABEL ORDERS (Pesanan Langganan Katering)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id VARCHAR(255) NOT NULL,
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    package_id BIGINT REFERENCES public.packages(id) ON DELETE SET NULL,
    package_name VARCHAR(255) NOT NULL,
    price_per_day NUMERIC(12, 2) NOT NULL,
    customer_name VARCHAR(255) NOT NULL,
    phone VARCHAR(50) NOT NULL,
    address TEXT NOT NULL,
    duration_days INTEGER NOT NULL CHECK (duration_days >= 1 AND duration_days <= 30),
    start_date DATE NOT NULL,
    notes TEXT DEFAULT '',
    payment_method VARCHAR(50) DEFAULT 'transfer_bank',
    total NUMERIC(14, 2) NOT NULL,
    status VARCHAR(50) DEFAULT 'menunggu' CHECK (
        status IN ('menunggu', 'dibayar', 'diproses', 'dikirim', 'selesai', 'dibatalkan')
    ),
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- Index pencarian pesanan
CREATE INDEX IF NOT EXISTS idx_orders_device_id ON public.orders (device_id);
CREATE INDEX IF NOT EXISTS idx_orders_user_id ON public.orders (user_id);
CREATE INDEX IF NOT EXISTS idx_orders_created_at ON public.orders (created_at DESC);

-- ==============================================================================
-- 5. ROW LEVEL SECURITY (RLS) & POLICIES
-- ==============================================================================

-- Aktifkan RLS
ALTER TABLE public.packages ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

-- Policy untuk Packages (Semua pengunjung dapat membaca katalog paket)
CREATE POLICY "Public Read Packages" 
    ON public.packages FOR SELECT 
    USING (true);

-- Policy untuk Orders
CREATE POLICY "Allow Insert Orders" 
    ON public.orders FOR INSERT 
    WITH CHECK (true);

CREATE POLICY "Allow Read Orders" 
    ON public.orders FOR SELECT 
    USING (true);

CREATE POLICY "Allow Update Orders" 
    ON public.orders FOR UPDATE 
    USING (true);

CREATE POLICY "Allow Delete Orders" 
    ON public.orders FOR DELETE 
    USING (true);

-- Policy untuk Profiles
CREATE POLICY "Users can view own profile" 
    ON public.profiles FOR SELECT 
    USING (auth.uid() = id);

CREATE POLICY "Users can update own profile" 
    ON public.profiles FOR UPDATE 
    USING (auth.uid() = id);

-- ==============================================================================
-- 6. TRIGGER OTOMATIS PROFIL SAAT USER BARU DAFTAR (SUPABASE AUTH)
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO public.profiles (id, name, phone, address, updated_at)
    VALUES (
        NEW.id,
        COALESCE(NEW.raw_user_meta_data->>'name', 'User FitBox'),
        COALESCE(NEW.raw_user_meta_data->>'phone', ''),
        COALESCE(NEW.raw_user_meta_data->>'address', ''),
        NOW()
    );
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();
